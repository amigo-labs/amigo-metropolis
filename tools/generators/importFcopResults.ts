// Import the original's Precinct Assault results page from a checkout of the RE
// repo (amigo-labs/fcop-reverse-engineering).
//
//   extracted/presentation/results.json  the page (mission/results.c 0x004080a0):
//                                        its 25 strings, four rects, the heads,
//                                        the level, the eleven columns, the footer
//
//     -> packages/client/src/render/results/fcopResults.generated.ts
//
// The font (Cfnt 3) and the text colours are the HUD's, imported by
// `gen:presentation` (render/hud/bitmapText.ts, fcopPresentation.generated.ts).
//
// Usage: bun run gen:results --re ../fcop-reverse-engineering
// Authoring-time only: the client reads the generated module, never the RE.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const ROOT = join(import.meta.dir, "..", "..");
const OUT_DIR = join(ROOT, "packages", "client", "src", "render", "results");
const OUT_TS = join(OUT_DIR, "fcopResults.generated.ts");

function argValue(flag: string): string | undefined {
  const i = process.argv.indexOf(flag);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

const reArg = argValue("--re") ?? process.env.FCOP_RE_REPO;
if (!reArg) {
  console.error("usage: bun run gen:results --re <RE checkout>");
  process.exit(2);
}
const RE = resolve(reArg);
const readJson = <T>(...p: string[]): T => JSON.parse(readFileSync(join(RE, ...p), "utf8")) as T;
const reCommit = (() => {
  const r = Bun.spawnSync(["git", "rev-parse", "--short", "HEAD"], { cwd: RE });
  return r.exitCode === 0 ? r.stdout.toString().trim() : "unknown";
})();

interface Line {
  y_text320: number;
  text?: string;
  figure_key?: number;
}
interface Results {
  texts: { index: number; text: string }[];
  rects: { what: string; rect640: number[]; colour: { rgb: number[] }; dim: number }[];
  heads: {
    left: { x_text320: string; y_text320: number; colour: number };
    right: { x_text320: string; y_text320: number; colour: number };
  };
  level: { x_text320: string; y_text320: number; colour: string };
  columns: { centre_x_text320: number; colour: number; side: string | null; lines: Line[] }[];
  footer: { x_text320: string; y_text320: number; colour: number };
}
const results = readJson<Results>("extracted", "presentation", "results.json");

// --- the centring rules, read from the export's C spellings -------------------
/** `(0xSPAN - width)/4 + 0xX`: the span and the offset, in 640 and 320 units. */
function centring(rule: string): { span: number; x: number } {
  const m = /^\((0x[0-9a-f]+) - width\)\/4 \+ (0x[0-9a-f]+)/.exec(rule);
  if (!m) throw new Error(`unexpected centring rule: ${rule}`);
  return { span: Number.parseInt(m[1], 16), x: Number.parseInt(m[2], 16) };
}
const headLeft = centring(results.heads.left.x_text320);
const headRight = centring(results.heads.right.x_text320);
const level = centring(results.level.x_text320);
const footer = centring(results.footer.x_text320);
const levelColours = /^(\d+) while the frame clock's bit (\d+) is set, (\d+) otherwise/.exec(
  results.level.colour,
);
if (!levelColours) throw new Error(`unexpected level colour: ${results.level.colour}`);

// --- the texts, with their colour-code bytes ----------------------------------
const texts = results.texts.map((t, i) => {
  if (t.index !== i) throw new Error(`text ${i} out of order`);
  return t.text;
});
if (texts.length !== 25) throw new Error(`expected 25 texts, got ${texts.length}`);

// --- the rects ---------------------------------------------------------------
const rects = results.rects.map((r) => {
  if (r.rect640.length !== 4) throw new Error(`rect ${r.what}`);
  return { what: r.what, rect: r.rect640, rgb: r.colour.rgb, dim: r.dim };
});

// --- the columns -------------------------------------------------------------
const columns = results.columns.map((c) => ({
  x: c.centre_x_text320,
  colour: c.colour,
  side: c.side === null ? -1 : c.side.startsWith("left") ? 0 : 1,
  lines: c.lines.map((l) => {
    if (l.figure_key !== undefined) return { y: l.y_text320, key: l.figure_key };
    if (l.text === undefined) throw new Error("a line with neither text nor figure");
    const index = texts.indexOf(l.text);
    if (index < 0) throw new Error(`line text not in the table: ${l.text}`);
    return { y: l.y_text320, text: index };
  }),
}));

const out = `// GENERATED by tools/generators/importFcopResults.ts from
// amigo-labs/fcop-reverse-engineering @ ${reCommit} — do not edit by hand.
// Re-run \`bun run gen:results --re <RE checkout>\`.
//
// The Precinct Assault results page (loader state 0xd, RE mission/results.c
// 0x004080a0; extracted/presentation/results.json): rects in 640 x 480 units,
// text positions in 320 x 240 (x2 at 640 x 480, the font's own offsets added),
// text colours are hud.json's palettes (the HUD's TEXT_COLOURS), the rects'
// colours their 5:5:5 words << 3. Every rect is drawn with dim 1, half alpha.

/** The page's 25 strings (0x00487160); bytes 0x0a..0x1f switch the colour to byte - 10. */
export const RESULTS_TEXTS: readonly string[] = ${JSON.stringify(texts)};
export const TEXT_WINNER = 0;
export const TEXT_LOSER = 1;
export const TEXT_LEVEL = 2;
export const TEXT_AGAIN = 22;
export const TEXT_NEXT = 23;
export const TEXT_QUIT = 24;

/** The four rects in draw order: page, left head (red), right head (blue), footer bar (green). */
export const RESULTS_RECTS: readonly {
  readonly what: string;
  /** x, y, width, height, 640 x 480 units. */
  readonly rect: readonly number[];
  readonly rgb: readonly number[];
  readonly dim: number;
}[] = ${JSON.stringify(rects)};

/** WINNER / LOSER over each head: x = (span - width) / 4 + x, y in 320 units. */
export const HEAD_SPAN = ${headLeft.span};
export const HEAD_LEFT_X = ${headLeft.x};
export const HEAD_RIGHT_X = ${headRight.x};
export const HEAD_Y = ${results.heads.left.y_text320};
export const HEAD_COLOUR = ${results.heads.left.colour};

/** LEVEL %02d (one viewport only), blinking on the frame clock's bit. */
export const LEVEL_SPAN = ${level.span};
export const LEVEL_X = ${level.x};
export const LEVEL_Y = ${results.level.y_text320};
export const LEVEL_COLOUR_ON = ${levelColours[1]};
export const LEVEL_BLINK_BIT = ${levelColours[2]};
export const LEVEL_COLOUR_OFF = ${levelColours[3]};

/** The footer line on the green bar. */
export const FOOTER_SPAN = ${footer.span};
export const FOOTER_X = ${footer.x};
export const FOOTER_Y = ${results.footer.y_text320};
export const FOOTER_COLOUR = ${results.footer.colour};

/**
 * The eleven columns in draw order: centre x (320 units), colour, side (-1 the
 * labels and heads, 0 the left side = team slot 0, 1 the right), and each line's
 * y (320 units) with a table string (\`text\`) or a player_stat key (\`key\`).
 */
export const RESULTS_COLUMNS: readonly {
  readonly x: number;
  readonly colour: number;
  readonly side: number;
  readonly lines: readonly { readonly y: number; readonly text?: number; readonly key?: number }[];
}[] = ${JSON.stringify(columns)};
`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT_TS, out);
const fmt = Bun.spawnSync(["bunx", "biome", "format", "--write", OUT_TS], { cwd: ROOT });
if (fmt.exitCode !== 0) throw new Error(`biome format failed: ${fmt.stderr.toString()}`);
console.log(`wrote ${OUT_TS} (RE @ ${reCommit})`);
